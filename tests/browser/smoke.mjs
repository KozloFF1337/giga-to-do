import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.GIGA_PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.GIGA_TEST_URL || 'http://localhost:5180';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const api = async (path, method = 'GET', body) => {
  const response = await fetch(base + '/api/' + path, {method,headers:body?{'Content-Type':'application/json'}:{},body:body?JSON.stringify(body):undefined});
  assert.ok(response.ok, `${method} ${path}: ${response.status} ${await (!response.ok ? response.text() : '')}`);
  return response.status === 204 ? null : response.json();
};
const stamp = Date.now();
try {
  await api('runtime', 'PUT', {mode:'Disabled'});
  await page.goto(base);
  await page.getByRole('button', {name:'Аналитика',exact:true}).waitFor();
  assert.equal(await page.locator('#boards button').count(),4);
  await page.getByRole('button', {name:'＋ Новая задача',exact:true}).click();
  await page.getByLabel('Описание задачи · промпт').fill(`UI smoke ${stamp}\n<script>window.unexpected=true</script>`);
  await page.getByLabel('Название · необязательно').fill(`UI smoke ${stamp}`);
  await page.getByLabel('Кто проверяет результат').selectOption('true');
  await page.getByRole('button',{name:'Создать',exact:true}).click();
  const card = page.locator('.card').filter({hasText:`UI smoke ${stamp}`});
  await card.waitFor();
  assert.ok(await card.evaluate(el=>el.classList.contains('human')));
  await card.click();
  await page.getByText('<script>window.unexpected=true</script>',{exact:false}).waitFor();
  assert.equal(await page.evaluate(()=>window.unexpected),undefined);
  await page.getByRole('button',{name:'Закрыть',exact:true}).click();
  await page.getByRole('button',{name:'Фронтенд',exact:true}).click();
  await page.getByRole('heading',{name:'Фронтенд',exact:true}).waitFor();
  assert.equal(await page.locator('.card').filter({hasText:`UI smoke ${stamp}`}).count(),0);
  await page.getByRole('button',{name:'Аналитика',exact:true}).click();
  await page.getByRole('heading',{name:'Аналитика',exact:true}).waitFor();
  await page.getByRole('button',{name:'＋ Создать повторение',exact:true}).click();
  await page.getByLabel('Описание задачи · промпт').fill(`Schedule smoke ${stamp}`);
  await page.getByRole('button',{name:'Ближайшие запуски',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#preview')?.textContent.length>5);
  await page.getByRole('button',{name:'Создать',exact:true}).click();
  await page.getByText(`Schedule smoke ${stamp}`,{exact:true}).waitFor();
  const scheduleRow=page.locator('#schedules tr').filter({hasText:`Schedule smoke ${stamp}`});
  await scheduleRow.getByRole('button',{name:'Изменить',exact:true}).click();
  await page.getByLabel('Интервал: часы').fill('2');
  await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await scheduleRow.getByText('Каждые 1 д. 2 ч.',{exact:true}).waitFor();
  await scheduleRow.getByRole('button',{name:'Пауза',exact:true}).click();
  await scheduleRow.getByRole('button',{name:'Включить',exact:true}).waitFor();
  await scheduleRow.getByRole('button',{name:'История',exact:true}).click();
  await page.getByText('Слотов пока нет',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Закрыть',exact:true}).click();
  const originalBoard=(await api('boards')).find(b=>b.id==='analytics');
  await page.getByRole('button',{name:'Настройки доски',exact:true}).click();
  await page.getByRole('button',{name:'Навыки и сценарии агентов',exact:true}).click();
  await page.locator('#agent-matrix details').first().waitFor();
  await page.getByRole('button',{name:'＋ Репозиторий',exact:true}).click();
  await page.getByLabel('Локальный репозиторий',{exact:true}).fill('/tmp/ui-only-repository');
  await page.getByRole('button',{name:'Убрать',exact:true}).click();
  await page.getByLabel('Модель · пусто — настройки Gigacode',{exact:true}).fill('ui-only');
  await page.getByRole('button',{name:'Сохранить',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  const updatedBoard=(await api('boards')).find(b=>b.id==='analytics');
  assert.equal(updatedBoard.model,'ui-only');
  assert.deepEqual(JSON.parse(updatedBoard.defaultRepositoriesJson),[],'Skill matrix is not mistaken for repository inputs');
  await api('boards/analytics','PUT',{...originalBoard,version:updatedBoard.version,defaultRepositories:JSON.parse(originalBoard.defaultRepositoriesJson)});
  const tasks = await api('tasks?boardId=analytics');
  const task = tasks.find(t=>t.title===`UI smoke ${stamp}`);
  assert.ok(task);
  const configuredLimit=(await api('runtime')).agentLimit;
  assert.ok(configuredLimit>=1&&configuredLimit<=100);
  await page.getByRole('button',{name:'＋ Новая задача',exact:true}).click();
  await page.getByLabel('Описание задачи · промпт').fill(`Dependency smoke ${stamp}`);
  await page.locator(`input[name="dependencyIds"][value="${task.id}"]`).check();
  await page.getByRole('button',{name:'Создать',exact:true}).click();
  const dependentCard=page.locator('.card').filter({hasText:`Dependency smoke ${stamp}`});
  await dependentCard.locator('.badge').filter({hasText:'Ждёт 1 задач'}).waitFor();
  const beforeMove=(await api('tasks?boardId=analytics')).filter(t=>t.stage==='ToDo');
  const dependentIndex=beforeMove.findIndex(t=>t.prompt===`Dependency smoke ${stamp}`);
  await dependentCard.getByRole('button',{name:'Выше',exact:true}).click();
  await page.waitForFunction(({title,index})=>document.querySelectorAll('.column[data-stage=ToDo] .card h3')[index]?.textContent===title,{title:`Dependency smoke ${stamp}`,index:dependentIndex-1});
  const dependent=(await api('tasks?boardId=analytics')).find(t=>t.prompt===`Dependency smoke ${stamp}`);
  assert.deepEqual(dependent.dependencyIds,[task.id]);
  const todo=(await api('tasks?boardId=analytics')).filter(t=>t.stage==='ToDo').map(t=>t.id);
  await api('tasks/reorder','POST',{boardId:'analytics',stage:'ToDo',ids:[dependent.id,task.id,...todo.filter(id=>id!==dependent.id&&id!==task.id)]});
  await api('runtime','PUT',{mode:'Mock'});
  for(let i=0;i<25;i++){
    const detail=await api('tasks/'+task.id);
    if(detail.task.stage==='InReview')break;
    if(i===24)throw new Error('Mock executor did not reach InReview');
    await new Promise(resolve=>setTimeout(resolve,500));
  }
  assert.equal((await api('tasks/'+dependent.id)).task.stage,'ToDo');
  await card.click();
  await page.getByRole('button',{name:'Принять',exact:true}).waitFor();
  await page.getByRole('button',{name:'Принять',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#task-meta')?.textContent.includes('Done'));
  await page.getByRole('button',{name:'Закрыть',exact:true}).click();
  for(let i=0;i<35;i++){
    if((await api('tasks/'+dependent.id)).task.stage==='Done')break;
    if(i===34)throw new Error('Dependency did not unblock after prerequisite Done');
    await new Promise(resolve=>setTimeout(resolve,500));
  }
  await api('runtime','PUT',{mode:'Disabled'});
  await page.waitForFunction(()=>document.querySelector('#runner').value==='Disabled');
  await page.locator('#toast').waitFor({state:'hidden'});
  await mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/board-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),390,'No horizontal document overflow on mobile');
  await page.screenshot({path:'artifacts/board-mobile.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS: tabs, creation, escaped prompt, independent boards, schedule preview/create/edit/toggle/history, settings/skill matrix/repository inputs, top blocked task skipped, Mock execution, manual review, global limit, desktop/mobile.');
} catch(error) {
  console.error('Browser errors:',errors);
  await mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/board-failure.png',fullPage:true});
  throw error;
} finally {
  await api('runtime','PUT',{mode:'Disabled'}).catch(()=>{});
  await browser.close();
}
